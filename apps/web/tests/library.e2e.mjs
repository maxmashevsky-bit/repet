import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { chromium, request, expect: baseExpect } = require(process.env.REPET_PLAYWRIGHT_MODULE || "playwright/test");
const expect = baseExpect.configure({ timeout: 15000 });
const baseURL = process.env.REPET_E2E_URL || "http://127.0.0.1:3001";
const artifacts = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../tmp/task02-library");

test("library: author creates/publishes; student finds a stable version; mobile and errors", { timeout: 180000 }, async (t) => {
  await mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.REPET_CHROME_PATH ? { executablePath: process.env.REPET_CHROME_PATH } : {}) });
  const pages = [];
  t.after(async () => {
    try {
      for (const [index, page] of pages.entries()) {
        if (!page.isClosed()) {
          t.diagnostic(`final page ${index}: ${page.url()}`);
          await page.screenshot({ path: path.join(artifacts, `final-${index}.png`), fullPage: true });
        }
      }
    } finally { await browser.close(); }
  });
  const teacherAPI = await request.newContext({ baseURL });
  const studentAPI = await request.newContext({ baseURL });
  t.after(() => Promise.all([teacherAPI.dispose(), studentAPI.dispose()]));
  const suffix = crypto.randomUUID();
  async function json(api, method, url, data, status = 200) {
    const res = await api.fetch(url, { method, ...(data ? { data } : {}) });
    assert.equal(res.status(), status, `${method} ${url}: ${await res.text()}`);
    return res.json();
  }
  const teacher = (await json(teacherAPI, "POST", "/api/v1/auth/register", { display_name: "Преподаватель библиотеки", email: `library-teacher-${suffix}@example.test`, password: "RepetTest123!", role: "tutor", accept_terms: true }, 201)).user;
  const student = (await json(studentAPI, "POST", "/api/v1/auth/register", { display_name: "Ученик библиотеки", email: `library-student-${suffix}@example.test`, password: "RepetTest123!", role: "student", accept_terms: true }, 201)).user;
  const invite = await json(teacherAPI, "POST", "/api/v1/invitations", { student_email: student.email }, 201);
  await json(studentAPI, "POST", `/api/v1/invitations/${invite.token}/accept`, {}, 201);
  const teacherContext = await browser.newContext({ storageState: await teacherAPI.storageState(), viewport: { width: 1440, height: 1000 } });
  const studentContext = await browser.newContext({ storageState: await studentAPI.storageState(), viewport: { width: 1440, height: 1000 } });
  const page = await teacherContext.newPage();
  const learner = await studentContext.newPage();
  pages.push(page, learner);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  learner.on("pageerror", (error) => errors.push(error.message));
  const keyRequests = [];
  let lessonCreations = 0;
  page.on("request", (req) => { if (req.method() === "POST" && /\/catalog\/courses\/[^/]+\/lessons$/.test(new URL(req.url()).pathname)) lessonCreations++; });
  learner.on("request", (req) => { if (req.url().includes("answer-keys")) keyRequests.push(req.url()); });
  await page.goto(baseURL + "/tasks");
  await page.getByRole("link", { name: "Библиотека", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Библиотека", exact: true })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Главное меню" }).getByRole("link")).toHaveCount(4);
  await expect(page.locator(".top-nav a.active")).toHaveText("Задания");
  await page.getByRole("link", { name: "Создать урок", exact: true }).first().click();
  await page.getByRole("button", { name: "Новый курс", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("Название курса", { exact: true }).fill("Математическая мастерская");
  await dialog.getByLabel("Направление", { exact: true }).selectOption("olympiad");
  await dialog.getByLabel("Класс от", { exact: true }).selectOption("5");
  await dialog.getByLabel("Класс до", { exact: true }).selectOption("6");
  await dialog.getByLabel("Сложность", { exact: true }).selectOption("2");
  await dialog.getByRole("button", { name: "Создать курс", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole("button", { name: "Новая тема", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Название темы", { exact: true }).fill("Числа и вычисления");
  await dialog.getByRole("button", { name: "Создать тему", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const title = "Считаем по шагам";
  const original = "Разберём, как изменяется число при прибавлении единицы.";
  await page.getByLabel("Название урока", { exact: true }).fill(title);
  await page.getByLabel("Краткое описание", { exact: true }).fill("От наблюдения к обоснованному решению.");
  await page.getByLabel("Текст урока", { exact: true }).fill(original);
  await page.getByRole("button", { name: "Добавить упражнение", exact: true }).click();
  await page.getByLabel("Тип упражнения", { exact: true }).selectOption("numeric");
  await page.getByLabel("Условие упражнения", { exact: true }).fill("Вычислите 834728 + 1.");
  await page.getByLabel("Правильный ответ", { exact: true }).fill("834729");
  await page.getByLabel("Закрытое пояснение", { exact: true }).fill(`private-explanation-${suffix}`);
  await page.getByRole("tab", { name: "Предпросмотр", exact: true }).click();
  await expect(page.locator(".material-preview")).toContainText(original);
  await expect(page.locator(".material-preview")).not.toContainText("834729");
  await expect(page.getByLabel("Правильный ответ", { exact: true })).toHaveCount(0);
  await page.getByRole("tab", { name: "Редактирование", exact: true }).click();
  await page.route("**/api/v1/catalog/lessons/*/exercises", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "unavailable" } }) }));
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click();
  await expect(page.locator(".material-error")).toBeVisible();
  await page.unroute("**/api/v1/catalog/lessons/*/exercises");
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click();
  await page.waitForURL(/\/tasks\/library\/[0-9a-f-]+\/edit$/);
  const lessonID = new URL(page.url()).pathname.split("/").at(-2);
  let draft = await json(teacherAPI, "GET", `/api/v1/catalog/lessons/${lessonID}`);
  assert.equal(draft.author_id, teacher.id);
  assert.equal(draft.status, "draft");
  assert.equal(draft.version.exercises.length, 1);
  assert.equal(lessonCreations, 1, "retry must not create a second lesson");
  assert.equal((await studentAPI.get(`/api/v1/catalog/lessons/${lessonID}`)).status(), 404);
  await page.reload();
  await expect(page.getByLabel("Правильный ответ", { exact: true })).toHaveValue("834729");
  await page.setViewportSize({ width: 375, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "editor overflow");
  await page.screenshot({ path: path.join(artifacts, "editor-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Опубликовать", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("Математическая мастерская");
  await page.getByRole("button", { name: "Подтвердить публикацию", exact: true }).click();
  await page.waitForURL(new RegExp(`/tasks/library/${lessonID}$`));
  await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await learner.goto(baseURL + "/tasks/library");
  await learner.getByRole("link").filter({ has: learner.getByRole("heading", { name: title, exact: true }) }).click();
  await expect(learner.locator(".material-prose")).toHaveText(original);
  await expect(learner.getByText("1 упражнение", { exact: true })).toBeVisible();
  await expect(learner.locator("body")).not.toContainText("834729");
  await expect(learner.locator("body")).not.toContainText(`private-explanation-${suffix}`);
  await expect(learner.getByRole("link", { name: "Редактировать", exact: true })).toHaveCount(0);
  await learner.goto(`${baseURL}/tasks/library/${lessonID}/edit`);
  await expect(learner.getByRole("heading", { name: "Редактор недоступен" })).toBeVisible();
  assert.equal(keyRequests.length, 0);
  await page.getByRole("link", { name: "Редактировать", exact: true }).click();
  await page.getByLabel("Текст урока", { exact: true }).fill("Черновая правка, ещё не опубликованная.");
  await page.getByLabel("Условие упражнения", { exact: true }).fill("Вычислите 834728 + 2.");
  await page.getByLabel("Правильный ответ", { exact: true }).fill("834730");
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click();
  await expect(page.getByText("Черновик сохранён.", { exact: true })).toBeVisible();
  await learner.goto(`${baseURL}/tasks/library/${lessonID}`);
  await expect(learner.locator(".material-prose")).toHaveText(original);
  await page.getByRole("link", { name: "В библиотеку", exact: true }).click();
  await page.waitForURL(`${baseURL}/tasks/library`);
  await page.getByLabel("Название урока", { exact: true }).fill("Черновая");
  await page.getByLabel("Название урока", { exact: true }).press("Enter");
  await expect(page.getByRole("heading", { name: "Уроков не найдено" })).toBeVisible();
  await page.getByRole("link", { name: "Сбросить", exact: true }).click();
  await page.getByLabel("Название урока", { exact: true }).fill("Считаем");
  await page.getByLabel("Название урока", { exact: true }).press("Enter");
  await page.getByLabel("Класс", { exact: true }).selectOption("5");
  await page.getByLabel("Тип подготовки", { exact: true }).selectOption("olympiad");
  await page.getByLabel("Сложность", { exact: true }).selectOption("2");
  await expect(page.getByLabel("Тема", { exact: true })).toBeEnabled();
  await page.getByLabel("Тема", { exact: true }).selectOption({ label: "Числа и вычисления" });
  await expect(page.locator(".material-card")).toHaveCount(1);
  draft = await json(teacherAPI, "GET", `/api/v1/catalog/lessons/${lessonID}`);
  const titles = ["Линейные уравнения", "Делимость чисел", "Дроби и проценты", "Системы уравнений", "Геометрические построения", "Арифметические задачи", "Закономерности", "Логические рассуждения", "Площади фигур", "Графики функций", "Сравнение чисел", "Задачи на движение"];
  for (let i = 0; i < titles.length; i++) {
    const track = ["school", "olympiad", "oge", "ege"][i % 4];
    const grade = track === "oge" ? 9 : track === "ege" ? 11 : 5;
    const lesson = await json(teacherAPI, "POST", `/api/v1/catalog/courses/${draft.course_id}/lessons`, { topic_id: draft.version.topic_id, title: titles[i], summary: "Математика: условие, рассуждение, решение.", content: "Прочитайте условие и обоснуйте решение.", track, grade_min: grade, grade_max: grade, difficulty: i % 5 + 1 }, 201);
    await json(teacherAPI, "POST", `/api/v1/catalog/lessons/${lesson.id}/publish`, {});
  }
  await page.getByRole("link", { name: "Сбросить", exact: true }).click();
  await expect(page.locator(".material-card")).toHaveCount(12);
  await page.screenshot({ path: path.join(artifacts, "catalog-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "Далее", exact: true }).click();
  await expect(page.locator(".material-card")).toHaveCount(1);
  await page.getByRole("button", { name: "Назад", exact: true }).click();
  await expect(page.locator(".material-card")).toHaveCount(12);
  await page.reload();
  await expect(page.locator(".material-card")).toHaveCount(12);
  await learner.setViewportSize({ width: 375, height: 900 });
  await learner.goto(baseURL + "/tasks/library");
  await expect(learner.locator(".material-card")).toHaveCount(12);
  assert.equal(await learner.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "mobile overflow");
  await learner.screenshot({ path: path.join(artifacts, "catalog-mobile.png"), fullPage: true });
  await learner.screenshot({ path: path.join(artifacts, "catalog-mobile-top.png") });
  await learner.goto(`${baseURL}/tasks/library/${lessonID}`);
  await expect(learner.locator(".material-prose")).toHaveText(original);
  assert.equal(await learner.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "reader overflow");
  await learner.screenshot({ path: path.join(artifacts, "lesson-mobile.png"), fullPage: true });
  await learner.route("**/api/v1/catalog/lessons?*", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "unavailable" } }) }));
  await learner.goto(baseURL + "/tasks/library");
  await expect(learner.locator(".material-error")).toBeVisible();
  await learner.unroute("**/api/v1/catalog/lessons?*");
  await learner.getByRole("button", { name: "Повторить", exact: true }).click();
  await expect(learner.locator(".material-card")).toHaveCount(12);
  let release;
  const gate = new Promise((resolve) => { release = resolve; });
  await learner.route("**/api/v1/catalog/lessons?*", async (route) => { await gate; await route.continue(); });
  await learner.reload();
  await expect(learner.getByText("Загружаем материалы…", { exact: true })).toBeVisible();
  release();
  await expect(learner.locator(".material-card")).toHaveCount(12);
  await learner.unroute("**/api/v1/catalog/lessons?*");
  await page.goto(`${baseURL}/tasks/library/${lessonID}`);
  await expect(page.locator(".material-prose")).toHaveText(original);
  await expect(page.getByRole("status")).toContainText("опубликованная версия");
  await page.getByRole("link", { name: "Редактировать", exact: true }).click();
  await page.getByRole("button", { name: "Опубликовать", exact: true }).click();
  await page.getByRole("button", { name: "Подтвердить публикацию", exact: true }).click();
  await page.waitForURL(new RegExp(`/tasks/library/${lessonID}$`));
  await learner.goto(`${baseURL}/tasks/library/${lessonID}`);
  // An existing learning attempt stays pinned; the catalog itself exposes the new publication.
  await expect(learner.locator(".material-prose")).toHaveText(original);
  assert.equal((await json(studentAPI, "GET", `/api/v1/catalog/lessons/${lessonID}`)).version.content,"Черновая правка, ещё не опубликованная.");
  await expect(learner.locator("body")).not.toContainText("834730");
  assert.equal((await json(teacherAPI, "GET", `/api/v1/catalog/lessons/${lessonID}/versions/1`)).version.content, original);
  assert.equal((await json(teacherAPI, "GET", `/api/v1/catalog/lessons/${lessonID}`)).version.exercises.length, 1);
  assert.deepEqual(errors, []);
  assert.equal(keyRequests.length, 0);
});
