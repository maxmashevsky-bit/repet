import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { chromium, request, expect: baseExpect } = require(process.env.REPET_PLAYWRIGHT_MODULE || "playwright/test");
const expect = baseExpect.configure({ timeout: 15000 });
const baseURL = process.env.REPET_E2E_URL || "http://127.0.0.1:3002";
const artifacts = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../tmp/task03-exercise-engine");

test("one lesson, five exercise types, real checking and teacher review", { timeout: 240000 }, async (t) => {
  await mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.REPET_CHROME_PATH ? { executablePath: process.env.REPET_CHROME_PATH } : {}) });
  const pages = [];
  t.after(async () => { try { for (const [index, page] of pages.entries()) { t.diagnostic(page.url()); await page.screenshot({ path: path.join(artifacts, `final-${index}.png`), fullPage: true }); } } finally { await browser.close(); } });
  const teacherAPI = await request.newContext({ baseURL });
  const studentAPI = await request.newContext({ baseURL });
  t.after(() => Promise.all([teacherAPI.dispose(), studentAPI.dispose()]));
  async function call(api, method, url, data, status = 200) {
    const response = await api.fetch(url, { method, ...(data ? { data } : {}) });
    assert.equal(response.status(), status, `${method} ${url}: ${await response.text()}`);
    return response.json();
  }
  const suffix = crypto.randomUUID();
  const register = (api, role) => call(api, "POST", "/api/v1/auth/register", { email: `${role}-${suffix}@example.test`, display_name: role === "tutor" ? "Автор упражнений" : "Ученик упражнений", password: "RepetTest123!", role, accept_terms: true }, 201);
  await register(teacherAPI, "tutor"); const { user: student } = await register(studentAPI, "student");
  const invitation = await call(teacherAPI, "POST", "/api/v1/invitations", { student_email: student.email }, 201);
  await call(studentAPI, "POST", `/api/v1/invitations/${invitation.token}/accept`, {}, 201);
  const base = "/api/v1/catalog";
  const course = await call(teacherAPI, "POST", `${base}/courses`, { title: "Практикум", description: "", track: "school", grade_min: 5, grade_max: 6, difficulty: 2, visibility: "linked_students" }, 201);
  const topic = await call(teacherAPI, "POST", `${base}/courses/${course.id}/topics`, { title: "Числа и рассуждения", description: "", parent_id: null, position: 0 }, 201);
  const lessonInput = { topic_id: topic.id, title: "Пять способов решения", summary: "Математический практикум", content: "Решите задания и обоснуйте выводы.", track: "school", grade_min: 5, grade_max: 6, difficulty: 2 };
  const lesson = await call(teacherAPI, "POST", `${base}/courses/${course.id}/lessons`, lessonInput, 201);
  await call(teacherAPI, "POST", `${base}/courses/${course.id}/publish`, {});
  await call(teacherAPI, "POST", `${base}/topics/${topic.id}/publish`, {});
  const author = await browser.newContext({ storageState: await teacherAPI.storageState(), viewport: { width: 1440, height: 1000 } });
  const reader = await browser.newContext({ storageState: await studentAPI.storageState(), viewport: { width: 1440, height: 1000 } });
  const page = await author.newPage(); const learner = await reader.newPage(); pages.push(page, learner);
  const errors = []; const keyRequests = []; let submissions = 0;
  for (const target of pages) target.on("pageerror", (error) => errors.push(error.message));
  learner.on("request", (req) => { if (req.url().includes("answer-keys")) keyRequests.push(req.url()); if (req.method() === "POST" && req.url().endsWith("/attempts")) submissions++; });
  await page.goto(`${baseURL}/tasks/library/${lesson.id}/edit`);
  for (const [index, kind] of ["single_choice", "multiple_choice", "numeric", "text", "long_text"].entries()) {
    await page.getByRole("button", { name: "Добавить упражнение", exact: true }).click();
    const editor = page.locator(".material-exercise-editor").nth(index);
    await editor.getByLabel("Тип упражнения", { exact: true }).selectOption(kind);
    await editor.getByLabel("Условие упражнения", { exact: true }).fill(["Выберите букву b.", "Выберите буквы a и c.", "Найдите половину единицы.", "Как называются эти углы?", "Обоснуйте своё рассуждение."][index]);
    if (kind.includes("choice")) await editor.getByLabel("Варианты ответа, каждый с новой строки", { exact: true }).fill("a\nb\nc");
    if (kind === "multiple_choice") { const group = editor.getByRole("group", { name: "Правильные ответы", exact: true }); await group.getByLabel("a", { exact: true }).check(); await group.getByLabel("c", { exact: true }).check(); }
    else if (kind === "single_choice") await editor.getByLabel("Правильный ответ", { exact: true }).selectOption("b");
    else if (kind !== "long_text") await editor.getByLabel("Правильный ответ", { exact: true }).fill(kind === "numeric" ? "1/2" : "равные углы");
    await editor.getByLabel("Закрытое пояснение", { exact: true }).fill("PRIVATE-ONLY-KEY");
  }
  await page.getByRole("tab", { name: "Предпросмотр", exact: true }).click();
  await expect(page.locator(".material-preview .engine-exercise")).toHaveCount(5);
  await expect(page.locator(".material-preview")).not.toContainText("PRIVATE-ONLY-KEY");
  await expect(page.locator(".material-preview").getByRole("button")).toHaveCount(0);
  await page.getByRole("tab", { name: "Редактирование", exact: true }).click();
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click();
  await expect(page.getByText("Черновик сохранён.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Опубликовать", exact: true }).click();
  await page.getByRole("button", { name: "Подтвердить публикацию", exact: true }).click();
  await page.waitForURL(new RegExp(`/tasks/library/${lesson.id}$`));
  await learner.goto(`${baseURL}/tasks/library/${lesson.id}`);
  await expect(learner.locator(".engine-exercise")).toHaveCount(5);
  const single = learner.locator('[data-exercise-kind="single_choice"]');
  await single.getByLabel("a", { exact: true }).check(); await single.getByRole("button", { name: "Проверить ответ" }).click();
  await expect(single.getByRole("status")).toHaveText("Неверно");
  await single.getByLabel("b", { exact: true }).check(); await single.getByRole("button", { name: "Проверить ответ" }).click();
  await expect(single.getByRole("status")).toHaveText("Верно");
  const multi = learner.locator('[data-exercise-kind="multiple_choice"]');
  await multi.getByLabel("a", { exact: true }).check(); await multi.getByRole("button", { name: "Проверить ответ" }).click();
  await expect(multi.getByRole("status")).toHaveText("Неверно");
  await multi.getByLabel("c", { exact: true }).check(); await multi.getByRole("button", { name: "Проверить ответ" }).click();
  await expect(multi.getByRole("status")).toHaveText("Верно");
  const numeric = learner.locator('[data-exercise-kind="numeric"]');
  await numeric.getByLabel("Число или дробь").fill("1/0"); const before = submissions;
  await numeric.getByRole("button", { name: "Проверить ответ" }).click(); await expect(numeric.getByRole("alert")).toBeVisible(); assert.equal(submissions, before);
  await numeric.getByLabel("Число или дробь").fill(" -2 / -4 ");
  let release; const gate = new Promise((resolve) => { release = resolve; });
  await learner.route("**/exercises/*/attempts", async (route) => { await gate; await route.continue(); });
  await numeric.getByRole("button", { name: "Проверить ответ" }).click();
  await expect(numeric.getByRole("status")).toHaveText("Проверяется…"); await expect(numeric.getByLabel("Число или дробь")).toBeDisabled(); release();
  await expect(numeric.getByRole("status")).toHaveText("Верно"); await learner.unroute("**/exercises/*/attempts");
  const short = learner.locator('[data-exercise-kind="text"]');
  await short.getByLabel("Короткий ответ").fill("  РАВНЫЕ   углы "); await short.getByLabel("Короткий ответ").press("Enter");
  await expect(short.getByRole("status")).toHaveText("Верно");
  const long = learner.locator('[data-exercise-kind="long_text"]');
  await long.getByLabel("Развёрнутое решение").fill("Пусть x = 1. Тогда из условия следует утверждение.");
  await long.getByRole("button", { name: "Отправить преподавателю" }).click(); await expect(long.getByRole("status")).toHaveText("Требует проверки преподавателем");
  await learner.reload(); await expect(learner.locator(".engine-correct")).toHaveCount(4); await expect(learner.locator(".engine-needs_review")).toHaveCount(1);
  const publicLesson = await call(studentAPI, "GET", `${base}/lessons/${lesson.id}`);
  assert.equal(JSON.stringify(publicLesson).includes("PRIVATE-ONLY-KEY"), false); assert.equal(JSON.stringify(publicLesson).includes("answer_key"), false);
  await page.getByRole("button", { name: "Обновить решения", exact: true }).click();
  const review = page.locator(".engine-review"); await expect(review).toHaveCount(1);
  await review.getByLabel("Неверно", { exact: true }).check(); await review.getByLabel(`Комментарий для ${student.display_name}`).fill("Нужно обосновать первый переход.");
  await review.getByRole("button", { name: "Сохранить проверку" }).click(); await expect(review.locator(".engine-feedback")).toContainText("Неверно");
  await learner.getByRole("button", { name: "Обновить результаты" }).click(); await expect(long.getByRole("status")).toHaveText("Неверно"); await expect(long.locator(".engine-feedback")).toContainText("первый переход");
  await numeric.getByLabel("Число или дробь").fill("0,5");
  await learner.route("**/exercises/*/attempts", (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "unavailable" } }) }));
  await numeric.getByRole("button", { name: "Проверить ответ" }).click(); await expect(numeric.getByRole("alert")).toContainText("Не удалось отправить");
  await learner.unroute("**/exercises/*/attempts"); await numeric.getByRole("button", { name: "Проверить ответ" }).click(); await expect(numeric.getByRole("status")).toHaveText("Верно");
  await learner.evaluate(() => window.scrollTo(0, 0));
  await learner.screenshot({ path: path.join(artifacts, "five-types-desktop.png"), fullPage: true });
  await learner.setViewportSize({ width: 375, height: 900 });
  await learner.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await learner.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "mobile overflow");
  await learner.screenshot({ path: path.join(artifacts, "five-types-mobile.png"), fullPage: true }); await learner.screenshot({ path: path.join(artifacts, "five-types-mobile-top.png") });
  await call(teacherAPI, "PUT", `${base}/lessons/${lesson.id}`, { ...lessonInput, content: "Новая публикация" }); await call(teacherAPI, "POST", `${base}/lessons/${lesson.id}/publish`, {});
  await numeric.getByLabel("Число или дробь").fill("2/4"); await numeric.getByRole("button", { name: "Проверить ответ" }).click(); await expect(numeric.getByRole("status")).toHaveText("Верно");
  await call(studentAPI,"POST",`${base}/lessons/${lesson.id}/exercises/${publicLesson.version.exercises.find(e=>e.kind==="numeric").id}/attempts`,{version_id:publicLesson.version.id,request_id:crypto.randomUUID(),answer:{value:"2/4"}},409);
  assert.deepEqual(keyRequests, []); assert.deepEqual(errors, []);
});
